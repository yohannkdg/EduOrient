function getLanguage() {
  return localStorage.getItem("eduorient-language") || "fr";
}

function t(key) {
  const language = getLanguage();
  return translations[language]?.[key] || translations.fr[key] || key;
}

function applyLanguage(language) {
  if (!["fr", "en"].includes(language)) return;

  localStorage.setItem("eduorient-language", language);
  document.documentElement.lang = language;

  // Masquer l'écran de choix après la sélection
  document.body.classList.add("language-selected");

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const key = element.dataset.i18n;
    if (translations[language][key] !== undefined) {
      element.textContent = translations[language][key];
    }
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach((element) => {
    const key = element.dataset.i18nPlaceholder;
    if (translations[language][key] !== undefined) {
      element.placeholder = translations[language][key];
    }
  });

  const toggle = document.getElementById("language-toggle");
  if (toggle) {
    toggle.textContent = language === "fr" ? "🇬🇧 EN" : "🇫🇷 FR";
  }

  document.dispatchEvent(
    new CustomEvent("languageChanged", { detail: { language } })
  );
}

function setLanguage(language) {
  applyLanguage(language);
  document.body.classList.add("language-selected");
}

window.EduOrientLanguage = {
  getLanguage,
  setLanguage,
  applyLanguage,
  t,
  translations
};

function initializeLanguage() {
  const savedLanguage = localStorage.getItem("eduorient-language");

  if (savedLanguage === "fr" || savedLanguage === "en") {
    applyLanguage(savedLanguage);
  }

  const toggle = document.getElementById("language-toggle");

  if (toggle && !toggle.dataset.languageListener) {
    toggle.dataset.languageListener = "true";

    toggle.addEventListener("click", () => {
      const newLanguage = getLanguage() === "fr" ? "en" : "fr";
      setLanguage(newLanguage);
    });
  }
}

if (document.readyState === "loading") {
  document.addEventListener("DOMContentLoaded", initializeLanguage);
} else {
  initializeLanguage();
}
